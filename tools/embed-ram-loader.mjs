import fs from 'node:fs';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
const root=new URL('../',import.meta.url);
const bytes=fs.readFileSync(new URL('build_ram_loader/loader.bin',root));
assert.ok(bytes.length>128&&bytes.length<8192,'SRAM loader must fit lower 8 KiB');
const exe=process.env.LOCALAPPDATA+'/Arduino15/packages/rak_rui/tools/arm-none-eabi-gcc/9-2019q4/bin/arm-none-eabi-nm.exe';
const symbols=execFileSync(exe,['-n',new URL('build_ram_loader/loader.elf',root).pathname.replace(/^\/([A-Z]:)/,'$1')],{encoding:'utf8'});
assert.match(symbols,/20000000 T loader_main/);
for(const line of symbols.trim().split('\n'))assert.ok(!/\bU\b/.test(line),'Unresolved SRAM dependency: '+line);
const rows=[];for(let i=0;i<bytes.length;i+=20)rows.push(' '+Array.from(bytes.subarray(i,i+20),b=>'0x'+b.toString(16).padStart(2,'0')).join(',')+',');
fs.writeFileSync(new URL('stm32/ram_loader_asset.h',root),'// Generated by tools/build-ram-loader.ps1; do not edit.\n#pragma once\n#include <stdint.h>\nstatic const uint8_t RAM_LOADER[] = {\n'+rows.join('\n')+'\n};\n');
console.log('SRAM loader: '+bytes.length+' bytes, fixed entry, no unresolved symbols.');
